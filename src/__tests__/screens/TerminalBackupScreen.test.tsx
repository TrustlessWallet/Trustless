import React from 'react';
import { act, fireEvent, render, waitFor } from '@testing-library/react-native';
import TerminalBackupScreen from '../../screens/TerminalBackupScreen';
import { useActiveWallet } from '../../contexts/WalletContext';
import { useWalletMode } from '../../contexts/WalletModeContext';
import * as Sharing from 'expo-sharing';
import * as Picker from 'expo-document-picker';
import * as Backup from '../../services/terminalBackup';
const mockOptions = jest.fn();
jest.mock('crypto', () => require('node:crypto'));
jest.mock('@react-navigation/native', () => ({ useIsFocused: () => true, useNavigation: () => ({ setOptions: mockOptions }) }));
jest.mock('../../contexts/WalletContext', () => ({ useActiveWallet: jest.fn() }));
jest.mock('../../contexts/WalletModeContext', () => ({ useWalletMode: jest.fn() }));
jest.mock('../../contexts/ThemeContext', () => ({ useTheme: () => ({ theme: { colors: { background: '#fff', primary: '#000', surface: '#eee', muted: '#888', border: '#ccc', bitcoin: '#f90' } } }) }));
jest.mock('react-native-safe-area-context', () => ({ useSafeAreaInsets: () => ({ top: 0, bottom: 0 }) }));
jest.mock('../../components/StyledInput', () => ({ StyledInput: require('react-native').TextInput }));
jest.mock('../../screens/TerminalSheetHeader', () => () => null);
jest.mock('../../services/terminalBackup', () => ({ createTerminalBackup: jest.fn(), inspectTerminalBackup: jest.fn(), restoreTerminalBackup: jest.fn(), disposeTerminalBackup: jest.fn().mockResolvedValue(undefined), removeTerminalBackupFile: jest.fn() }));
jest.mock('expo-document-picker', () => ({ getDocumentAsync: jest.fn() }));
jest.mock('expo-sharing', () => ({ shareAsync: jest.fn(), isAvailableAsync: jest.fn() }));
jest.mock('expo-file-system', () => ({ Paths: { cache: 'file:///cache' }, File: class { uri = 'file:///owned'; exists = true; size = 500; copy() {} } }));
const props = { walletId: 'a', network: 'mainnet' as const, onClose: jest.fn() };
beforeEach(() => {
  jest.clearAllMocks();
  (useActiveWallet as jest.Mock).mockReturnValue({ id: 'a', type: 'standard', xpub: 'xpub-test' });
  (useWalletMode as jest.Mock).mockReturnValue({ cashierState: 'off' });
  (Sharing.isAvailableAsync as jest.Mock).mockResolvedValue(true);
  (Sharing.shareAsync as jest.Mock).mockResolvedValue(undefined);
  (Backup.createTerminalBackup as jest.Mock).mockResolvedValue({ uri: 'file:///backup' });
  (Picker.getDocumentAsync as jest.Mock).mockResolvedValue({ canceled: false, assets: [{ uri: 'file:///selected', name: 'shop.trustless' }] });
});
it('blocks empty passwords, catches mismatch and shares only one encrypted backup for repeated taps', async () => {
  const view = render(<TerminalBackupScreen {...props} />);
  expect(view.getByLabelText('Create backup').props.accessibilityState.disabled).toBe(true);
  fireEvent.changeText(view.getByLabelText('Backup password'), 'correct horse battery staple');
  fireEvent.changeText(view.getByLabelText('Confirm backup password'), 'different password');
  fireEvent.press(view.getByLabelText('Create backup'));
  await waitFor(() => expect(view.getByText('Passwords don’t match.')).toBeTruthy());
  fireEvent.changeText(view.getByLabelText('Confirm backup password'), 'correct horse battery staple');
  fireEvent.press(view.getByLabelText('Create backup')); fireEvent.press(view.getByLabelText('Create backup'));
  await waitFor(() => expect(Sharing.shareAsync).toHaveBeenCalledTimes(1));
  expect(Backup.createTerminalBackup).toHaveBeenCalledTimes(1);
  expect(Backup.removeTerminalBackupFile).toHaveBeenCalledWith('file:///backup');
});
it('reviews the unlocked backup before a separate restore action and disposes it after leaving owner scope', async () => {
  const preview = { createdAt: 1000, sales: 12, refunds: 2, items: 3 };
  (Backup.inspectTerminalBackup as jest.Mock).mockResolvedValue(preview);
  const view = render(<TerminalBackupScreen {...props} />);
  fireEvent.press(view.getByLabelText('Restore backup tab')); fireEvent.press(view.getByLabelText('Choose backup'));
  await waitFor(() => expect(view.getByLabelText('Restore backup password')).toBeTruthy());
  fireEvent.changeText(view.getByLabelText('Restore backup password'), 'correct horse battery staple');
  fireEvent.press(view.getByLabelText('Unlock backup'));
  await waitFor(() => expect(view.getByText('12 sales · 2 refunds · 3 items')).toBeTruthy());
  expect(Backup.restoreTerminalBackup).not.toHaveBeenCalled();
  (useWalletMode as jest.Mock).mockReturnValue({ cashierState: 'locked' });
  view.rerender(<TerminalBackupScreen {...props} />);
  await waitFor(() => expect(Backup.disposeTerminalBackup).toHaveBeenCalledWith(preview));
  expect(view.queryByLabelText('Restore backup')).toBeNull();
});
it('does not apply a picker result after the wallet changes', async () => {
  let select!: (value: unknown) => void;
  (Picker.getDocumentAsync as jest.Mock).mockImplementation(() => new Promise(resolve => { select = resolve; }));
  const view = render(<TerminalBackupScreen {...props} />);
  fireEvent.press(view.getByLabelText('Restore backup tab')); fireEvent.press(view.getByLabelText('Choose backup'));
  (useActiveWallet as jest.Mock).mockReturnValue({ id: 'other', type: 'standard', xpub: 'other' });
  view.rerender(<TerminalBackupScreen {...props} />);
  await act(async () => select({ canceled: false, assets: [{ uri: 'file:///stale', name: 'stale' }] }));
  expect(view.queryByText('stale')).toBeNull();
  expect(Backup.inspectTerminalBackup).not.toHaveBeenCalled();
});
